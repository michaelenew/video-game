//! **Cells and leaders**, with no protocol to speak of
//! (`docs/design/exploration/0018_crowds.md` §5).
//!
//! A **cell** is a region's membership: the peers whose fighters are members
//! of the region, which is a function of confirmed positions and so the same
//! list on every machine. Its **leaders** are the `k` members with the lowest
//! `hash(id, region, epoch)`: every member computes the same list from the
//! same world, a member gone from the world (`World::away`) is gone from the
//! list on the same frame everywhere, and the hash rotates the job round the
//! cell every epoch. Nobody is elected; it is read off.
//!
//! A **super-region** is a hexagon of seven regions, and its leaders are
//! chosen among its live children's leaders by the same hash, so the
//! hierarchy is the same rule at every level, and its aggregate is the sum
//! of its children's (`sim::crowd::Aggregate::sum`): cells of cells is
//! summing.
//!
//! Pure functions over the world and the roster; the lines they talk over
//! are [`crate::crowd`].

use sim::World;
use sim::region::{Grid, RegionId};

/// How many leaders a cell keeps at once: enough that all of them dropping
/// inside one epoch is not worth planning for (the way Kademlia sizes a
/// bucket), and few enough that the job is not everybody's.
pub const LEADERS: usize = 3;

/// A peer as the roster names it: its seat, and the id it joined with.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub struct Member {
    pub seat: usize,
    pub id: u64,
}

/// `hash(id, region, epoch)`: the one number a cell orders itself by.
pub fn rank(id: u64, region: RegionId, epoch: u16) -> u64 {
    let mut h = id ^ (region.word() as u64) << 32 ^ (epoch as u64) << 24;
    h ^= h >> 31;
    h = h.wrapping_mul(0x9E37_79B9_7F4A_7C15);
    h ^= h >> 29;
    h = h.wrapping_mul(0xBF58_476D_1CE4_E5B9);
    h ^ (h >> 32)
}

/// **The cell of `region`**: every roster member whose fighter is a member
/// of it this frame (the grid's membership, one horizon further out for the
/// inputs -- `regions::session::Peer::admits`), in seat order.
pub fn cell(world: &World, grid: &Grid, roster: &[Member], region: RegionId) -> Vec<Member> {
    let origin = world.map_origin();
    let reach = grid.membership().add(grid.horizon());
    roster
        .iter()
        .filter(|m| {
            world.is_present(m.seat)
                && grid
                    .gap(region, world.players[m.seat].pos.add(origin))
                    .raw()
                    <= reach.raw()
        })
        .copied()
        .collect()
}

/// **The leaders of a cell** for `epoch`: the [`LEADERS`] lowest-ranked of
/// its members, lowest first. Fewer if the cell is smaller.
pub fn leaders(members: &[Member], region: RegionId, epoch: u16) -> Vec<Member> {
    let mut ranked: Vec<(u64, Member)> = members
        .iter()
        .map(|m| (rank(m.id, region, epoch), *m))
        .collect();
    ranked.sort_by_key(|(r, m)| (*r, m.seat));
    ranked.into_iter().take(LEADERS).map(|(_, m)| m).collect()
}

/// Is this peer a leader of the region's cell this epoch?
pub fn leads(
    world: &World,
    grid: &Grid,
    roster: &[Member],
    region: RegionId,
    epoch: u16,
    me: usize,
) -> bool {
    leaders(&cell(world, grid, roster, region), region, epoch)
        .iter()
        .any(|m| m.seat == me)
}

/// **Every region this peer leads** this epoch: of the regions its own
/// fighter is a member of.
pub fn led_by(
    world: &World,
    grid: &Grid,
    roster: &[Member],
    epoch: u16,
    me: usize,
) -> Vec<RegionId> {
    if !world.is_present(me) {
        return Vec::new();
    }
    let at = world.players[me].pos.add(world.map_origin());
    let mut out = Vec::new();
    let home = grid.home(at);
    for r in std::iter::once(home).chain(home.neighbours()) {
        if grid.gap(r, at).raw() <= grid.membership().add(grid.horizon()).raw()
            && leads(world, grid, roster, r, epoch, me)
        {
            out.push(r);
        }
    }
    out
}

// ---------------------------------------------------------------------------
// Super-regions: hexagons of seven
// ---------------------------------------------------------------------------

/// The lattice of super-region centres: every seventh hexagon, generated by
/// `(2, 1)` and `(-1, 3)` in axial coordinates (determinant seven), so each
/// region is within one step of exactly one centre.
const GEN_A: (i32, i32) = (2, 1);
const GEN_B: (i32, i32) = (-1, 3);

/// Hexagonal distance between two axial coordinates.
fn hex_dist(a: (i32, i32), b: (i32, i32)) -> i32 {
    let (dq, dr) = (a.0 - b.0, a.1 - b.1);
    dq.abs().max(dr.abs()).max((dq + dr).abs())
}

/// **The super-region a region is in**, named by its centre region.
pub fn super_of(region: RegionId) -> RegionId {
    let (q, r) = (region.q as i32, region.r as i32);
    // Solve for the lattice coordinates in the real numbers, then look at
    // the neighbouring lattice points for the one within a step.
    // q = 2i - j, r = i + 3j  =>  i = (3q + r) / 7, j = (2r - q) / 7.
    let i0 = (3 * q + r).div_euclid(7);
    let j0 = (2 * r - q).div_euclid(7);
    for di in -1..=1 {
        for dj in -1..=1 {
            let (i, j) = (i0 + di, j0 + dj);
            let c = (i * GEN_A.0 + j * GEN_B.0, i * GEN_A.1 + j * GEN_B.1);
            if hex_dist(c, (q, r)) <= 1 {
                return RegionId::new(c.0 as i16, c.1 as i16);
            }
        }
    }
    // Unreachable for a sound lattice; the region itself keeps the hierarchy
    // honest rather than silent.
    region
}

/// The seven regions of a super-region, its centre first.
pub fn children(centre: RegionId) -> [RegionId; 7] {
    let mut out = [centre; 7];
    out[1..].copy_from_slice(&centre.neighbours());
    out
}

/// A child's offset from its super-region's centre, in decimetres on the
/// floor: what `Aggregate::sum` shifts a child's middle by.
pub fn offset_dm(grid: &Grid, centre: RegionId, child: RegionId) -> [i32; 2] {
    let (cx, cz) = grid.centre(centre);
    let (x, z) = grid.centre(child);
    [
        (x.sub(cx).raw() as i64 * 10 / 65_536) as i32,
        (z.sub(cz).raw() as i64 * 10 / 65_536) as i32,
    ]
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_region_is_within_a_step_of_exactly_one_centre_and_a_super_region_has_seven() {
        let mut counts = std::collections::HashMap::new();
        for q in -30..=30 {
            for r in -30..=30 {
                let id = RegionId::new(q, r);
                let c = super_of(id);
                assert!(
                    hex_dist((c.q as i32, c.r as i32), (q as i32, r as i32)) <= 1,
                    "{id:?} -> {c:?}"
                );
                assert_eq!(super_of(c), c, "a centre is its own super-region");
                *counts.entry(c).or_insert(0) += 1;
            }
        }
        // Away from the window's edge every centre has exactly seven.
        for (c, n) in counts {
            if c.q.abs() < 25 && c.r.abs() < 25 {
                assert_eq!(n, 7, "{c:?}");
            }
        }
        for child in children(RegionId::new(2, 1)) {
            assert_eq!(super_of(child), RegionId::new(2, 1));
        }
    }

    #[test]
    fn leaders_rotate_with_the_epoch_and_a_member_gone_is_gone_at_once() {
        let members: Vec<Member> = (0..8)
            .map(|seat| Member {
                seat,
                id: 1000 + seat as u64 * 7919,
            })
            .collect();
        let region = RegionId::new(3, -2);
        let a = leaders(&members, region, 1);
        let b = leaders(&members, region, 2);
        assert_eq!(a.len(), LEADERS);
        assert_ne!(a, b, "the job moves round the cell");
        // The same list from the same members, however they are ordered.
        let mut shuffled = members.clone();
        shuffled.reverse();
        assert_eq!(leaders(&shuffled, region, 1), a);
        // One gone: the rest keep their order, and the next in line steps up.
        let gone = a[0];
        let rest: Vec<Member> = members.iter().copied().filter(|m| *m != gone).collect();
        let c = leaders(&rest, region, 1);
        assert_eq!(c[0], a[1]);
        assert_eq!(c[1], a[2]);
        assert!(!c.contains(&gone));
    }
}
